#!/usr/bin/env python3
"""Fail-closed provenance check for Spectre 7.1.8 staged ISO module overlay.
No writes in this program. Candidate qualification requires the previous full cryptographic pilot.
"""
import argparse
import csv
import filecmp
import hashlib
import os
from pathlib import Path
import subprocess
import sys

EXPECTED = 6825

def need(test, message):
    if not test:
        raise RuntimeError(message)

def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as fp:
        for block in iter(lambda: fp.read(4 * 1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()

def modules(tree):
    root = tree / 'kernel'
    need(root.is_dir() and not root.is_symlink(), f'Module kernel dir absent/linked: {root}')
    paths = {}
    for parent, dirs, files in os.walk(root, followlinks=False):
        need(not Path(parent).is_symlink(), f'Unsafe module directory: {parent}')
        for d in dirs:
            need(not (Path(parent) / d).is_symlink(), f'Linked module directory: {parent}/{d}')
        for name in files:
            path = Path(parent) / name
            if name.endswith(('.ko.xz', '.ko.zst', '.ko.gz')):
                raise RuntimeError(f'Unexpected compressed module: {path}')
            if name.endswith('.ko'):
                need(path.is_file() and not path.is_symlink(), f'Unsafe module: {path}')
                paths[path.relative_to(tree).as_posix()] = path
    need(len(paths) == EXPECTED, f'Expected {EXPECTED} modules in {tree}, found {len(paths)}')
    return paths

def order(tree, file_set):
    p = tree / 'modules.order'
    need(p.is_file() and not p.is_symlink(), f'Missing/untrusted modules.order: {p}')
    lines = [line.strip() for line in p.read_text().splitlines() if line.strip()]
    need(len(lines) == EXPECTED and len(set(lines)) == EXPECTED,
         f'Invalid modules.order count/duplicates: {p}')
    need(set(lines) == set(file_set), f'modules.order does not match module inventory: {p}')
    return p

def check_dependencies(tree, file_set):
    for meta in ('modules.dep', 'modules.alias', 'modules.builtin', 'modules.builtin.modinfo'):
        p = tree / meta
        need(p.is_file() and p.stat().st_size > 0 and not p.is_symlink(), f'Missing metadata: {p}')
    owners = set()
    for line in (tree / 'modules.dep').read_text().splitlines():
        if not line.strip():
            continue
        need(':' in line, f'Bad dependency entry: {line}')
        owner, deps = line.split(':', 1)
        need(owner in file_set and owner not in owners, f'Bad dependency owner: {owner}')
        owners.add(owner)
        for dependency in deps.split():
            need(dependency in file_set, f'Unresolved dependency path: {dependency}')
    need(owners == set(file_set), f'Dependency owners missing/extra in {tree}')

def match_kernel(baseline, source, krel):
    for name in (f'vmlinuz-{krel}', f'config-{krel}'):
        a, b = baseline / 'boot' / name, source / 'boot' / name
        need(a.is_file() and b.is_file(), f'Missing kernel provenance artifact: {name}')
        need(filecmp.cmp(a, b, shallow=False), f'Kernel identity MISMATCH: {name}')
    print('[PASS] Kernel binary and build configuration exactly match the trusted baseline.', flush=True)

def check_manifest(candidate, paths):
    # Candidate generated by the already-completed full cryptographic validation run.
    run = candidate.parents[3]
    qualification, manifest = run / 'qualification.txt', run / 'size-manifest.tsv'
    need(qualification.is_file() and qualification.read_text().strip() ==
         'FULL_ISOLATED_CRYPTO_AND_DEPENDENCY_PASS',
         f'Missing successful full cryptographic run marker: {qualification}')
    need(manifest.is_file(), f'Missing digest manifest: {manifest}')
    seen = set()
    with manifest.open(newline='') as fp:
        reader = csv.DictReader(fp, delimiter='\t')
        need(reader.fieldnames == ['path', 'before_bytes', 'after_bytes', 'sha256_optimized'],
             'Unexpected isolated size manifest schema')
        for item in reader:
            rel = item['path']
            need(rel in paths and rel not in seen, f'Unexpected/duplicate manifest path: {rel}')
            seen.add(rel)
            need(paths[rel].stat().st_size == int(item['after_bytes']), f'Size changed: {rel}')
            need(sha(paths[rel]) == item['sha256_optimized'], f'Digest changed since full qualification: {rel}')
    need(seen == set(paths), f'Manifest missing {len(set(paths)-seen)} modules')
    print(f'[PASS] All {len(seen)} optimized module SHA-256 digests match the qualified run.', flush=True)

def modinfo(path, field):
    return subprocess.check_output(['modinfo', '-F', field, str(path)], text=True).strip()

def critical(baseline, candidate, files_a, files_b, krel):
    for mod in ('vmd', 'nvme', 'ahci'):
        matches = [p for rel,p in files_b.items() if rel.endswith('/' + mod + '.ko')]
        need(len(matches) == 1, f'Missing/ambiguous optimized {mod}')
        optimized = matches[0]
        rel = optimized.relative_to(candidate).as_posix()
        original = files_a[rel]
        need(modinfo(optimized, 'vermagic') == modinfo(original, 'vermagic'), f'{mod} vermagic changed')
        need(modinfo(optimized, 'vermagic').startswith(krel + ' '), f'{mod} kernel mismatch')
        need(modinfo(optimized, 'depends') == modinfo(original, 'depends'), f'{mod} dependency identity changed')
        need(modinfo(optimized, 'signer') and modinfo(optimized, 'signer') == modinfo(original, 'signer'),
             f'{mod} signer mismatch')
        need(modinfo(optimized, 'sig_hashalgo') == 'sha512', f'{mod} signature hash metadata mismatch')
    print('[PASS] VMD, NVMe, AHCI: expected vermagic, signer and dependency identity.', flush=True)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--mode', choices=('source', 'integrated'), required=True)
    parser.add_argument('--candidate', type=Path, required=True)
    parser.add_argument('--baseline', type=Path, required=True)
    parser.add_argument('--target', type=Path, required=True)
    parser.add_argument('--krel', required=True)
    opts = parser.parse_args()
    candidate, baseline, target = (p.resolve(strict=True) for p in
                                   (opts.candidate, opts.baseline, opts.target))
    krel = opts.krel
    need(krel == '7.1.8-spectre', f'Unexpected kernel version: {krel}')
    need(candidate != baseline and candidate != target and baseline != target,
         'Candidate, baseline and target must be independent paths')
    candidate_mods = modules(candidate)
    order(candidate, candidate_mods)
    check_dependencies(candidate, candidate_mods)
    check_manifest(candidate, candidate_mods)
    baseline_mods = modules(baseline / 'lib' / 'modules' / krel)
    order(baseline / 'lib' / 'modules' / krel, baseline_mods)
    need(set(baseline_mods) == set(candidate_mods), 'Candidate and baseline module names differ')
    critical(baseline / 'lib' / 'modules' / krel, candidate,
             baseline_mods, candidate_mods, krel)
    if opts.mode == 'source':
        match_kernel(baseline, target, krel)
        source_tree = target / 'lib' / 'modules' / krel
        source_mods = modules(source_tree)
        order(source_tree, source_mods)
        need(set(source_mods) == set(baseline_mods), 'Source image module list differs from baseline')
        print('[INFO] Byte-comparing every source-image module with its baseline...', flush=True)
        for rel, source in sorted(source_mods.items()):
            need(filecmp.cmp(source, baseline_mods[rel], shallow=False),
                 f'Source image has a DIFFERENT original module: {rel}')
        print('[PASS] All 6,825 original source-image modules exactly match the baseline.', flush=True)
    else:
        match_kernel(baseline, target, krel)
        target_tree = target / 'lib' / 'modules' / krel
        installed_mods = modules(target_tree)
        order(target_tree, installed_mods)
        check_dependencies(target_tree, installed_mods)
        need(set(candidate_mods) == set(installed_mods), 'Integrated module inventory changed')
        for rel, p in sorted(installed_mods.items()):
            need(filecmp.cmp(candidate_mods[rel], p, shallow=False), f'Copy differs: {rel}')
        size = sum(path.stat().st_size for path in installed_mods.values())
        need(size < 950*1024*1024, f'Integrated modules suspiciously large: {size} bytes')
        for extra in ('source', 'build'):
            need(not (target_tree / extra).is_symlink(), f'Development-only link in staged OS: {extra}')
        print(f'[PASS] All 6,825 integrated module bytes match; total {size/1024/1024:.0f} MiB.', flush=True)
    print('[PASS] SPECTRE VERIFIED MODULE BRIDGE AUDIT', flush=True)

if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, subprocess.CalledProcessError, ValueError) as exc:
        print(f'[STOP] {exc}', file=sys.stderr)
        sys.exit(1)
